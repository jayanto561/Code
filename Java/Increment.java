public class Increment {
    public static void main(String[] args) {
        int x=10;
        System.out.println(x++);
                System.out.println(x);

                int y=2;
                System.out.println(++y);
        System.out.println(y);
        

        int a =20;
        System.out.println(a--);
        System.out.println(a);
       
        int b= 40;
        System.out.println(--b);
        System.out.println(b);

        int j=23;
        int h =j++;
        System.out.println(j+" "+h);
    }
}
